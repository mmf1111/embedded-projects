/**************************************************************************************
 * ?  ? : I2C??????
 * ?  ? : ?
 * ??? : ?
 **************************************************************************************/
void I2C_SendData(u8 dat)		
{
    u8 i=8;
    for(i=0; i<8; i++)
    {
        SCL  = 0;
        Delay10us();
        if(dat & 0x80) SDA  = 1;
        else SDA  = 0;
        Delay10us();
        SCL = 1;
        dat <<= 1;
        Delay10us();
    }
    SCL  = 0;  
}

