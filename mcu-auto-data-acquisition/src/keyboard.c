u8 keyboard_scan(void)
{
	  static u8 X_temp,Y_temp,temp;
	
	  X_temp=0xF0;        //?????
	  Y_temp=0x0F;        //?????
	  P3M1 &= 0xF3;	P3M0 |= 0x0C;	  //??P3.2~P3.3??????
	  P4M1 &= 0xEB;	P4M0 |= 0x14;	  //??P4.2,P4.4??????
	
    ROW1=1;ROW2=1;                //???
	  COL1=0;COL2=0;                //???
	
		//????IO??????,????
	  delay_ms(10);
	  P3M1 &= 0xF3;	P3M0 &= 0xF3;	  //??P3.2~P3.3?????
    delay_ms(10);
	
		if(ROW1 == 0)         //???1????????
		{
			delay_ms(10);
			if(ROW1 == 0)
			Y_temp &= 0x0E;	
		}
		if(ROW2 == 0)         //???2????????
		{
			delay_ms(10);
			if(ROW2 == 0)
			Y_temp &= 0x0D;	
		}
	  
	  P3M1 &= 0xF3;	P3M0 |= 0x0C;	  //??P3.2~P3.3??????
	  P4M1 &= 0xEB;	P4M0 |= 0x14;	  //??P4.2,P4.4??????
	
		ROW1=0;ROW2=0;                //???
	  COL1=1;COL2=1;                //???
	
		//????IO??????,????
		delay_ms(10);
	  P4M1 &= 0xEB;	P4M0 &= 0xEB;	  //??P4.2?P4.4?????
    delay_ms(10);
	
		if(COL1 == 0)         //???1????????
		{
			delay_ms(10);
			if(COL1 == 0)
			X_temp &= 0xE0;	
		}
		if(COL2 == 0)         //???2????????
		{
			delay_ms(10);
			if(COL2 == 0)
			X_temp &= 0xD0;	
		}
		
		//????????,??????????
		temp = X_temp|Y_temp;
	  temp = ~temp;
			
		//????????????????????
    switch (temp)
    {   
			case 0x11:return BUTTON1_PRESSED;	  //S4??
		  case 0x12:return BUTTON2_PRESSED;	  //S5??	
		  case 0x21:return BUTTON5_PRESSED;	  //S8??
		  case 0x22:return BUTTON6_PRESSED;	  //S9??
		  default:  return BUTTONS_RELEASED; 		
    }                 
} 